const ALIAS = { 3: 'CSP-J', 4: 'GESP 7级', 5: 'CSP-S', 6: 'USACO金', 7: '省选' };

async function main() {
  console.log('=== 知识点导入（去重 + 难度分级）===\n');
  const existing = await prisma.knowledgePoint.findMany();
  const existingNames = new Set(existing.map(k => k.name));
  console.log(`现有知识点: ${existing.length} 个`);

  let created = 0, skipped = 0;
  const createdList = [];

  for (const p of POINTS) {
    // 显式匹配现有 → 跳过
    if (p.match && existingNames.has(p.match)) { skipped++; continue; }
    // 同名去重
    if (existingNames.has(p.name)) { skipped++; continue; }

    const kp = await prisma.knowledgePoint.create({
      data: {
        name: p.name,
        level: p.level,
        levelAlias: ALIAS[p.level],
        category: p.category,
      },
    });
    existingNames.add(p.name);
    createdList.push(`[L${p.level}] ${p.name} (${p.category})`);
    created++;
  }

  console.log(`\n✅ 新建: ${created} 个，跳过(重复/已覆盖): ${skipped} 个`);
  console.log('\n新建清单:');
  createdList.forEach(s => console.log('  ' + s));

  const total = await prisma.knowledgePoint.count();
  console.log(`\n知识点总数: ${total}`);
  await prisma.$disconnect();
}
main();
